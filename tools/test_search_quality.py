def run_tests():
    good = []
    weak = []
    bad  = []

    total = len(TEST_QUESTIONS)
    print(f"\n{'='*65}")
    print(f"  ТЕСТ КАЧЕСТВА ПОИСКА — {total} вопросов")
    print(f"{'='*65}\n")

    for question, hint in TEST_QUESTIONS:
        try:
            results = search(question)
        except Exception as e:
            bad.append((question, hint, f"ОШИБКА: {e}", []))
            print(f"❌  {question!r}")
            print(f"    → ОШИБКА: {e}\n")
            continue

        if not results:
            bad.append((question, hint, "нет результатов", []))
            print(f"❌  {question!r}")
            print(f"    → нет результатов (ожидалось: {hint})\n")
            continue

        best = results[0]
        score = best.score
        snippet = best.text[:120].replace("\n", " ").strip()
        page = best.page_title or best.page_url

        if score >= SCORE_GOOD:
            good.append((question, hint, score, page, snippet))
            print(f"✅  {question!r}")
            print(f"    score={score:.3f} | {page}")
            print(f"    «{snippet}...»\n")
        elif score >= SCORE_WEAK:
            weak.append((question, hint, score, page, snippet))
            print(f"⚠️  {question!r}")
            print(f"    score={score:.3f} | {page}")
            print(f"    «{snippet}...»\n")
        else:
            bad.append((question, hint, f"score={score:.3f}", results))
            print(f"❌  {question!r}")
            print(f"    score={score:.3f} — ниже порога (ожидалось: {hint})")
            print(f"    «{snippet}...»\n")

    # ── Итог ────────────────────────────────────────────────────────────────
    print(f"{'='*65}")
    print(f"  ИТОГ: ✅ {len(good)} хорошо  |  ⚠️ {len(weak)} слабо  |  ❌ {len(bad)} не найдено")
    print(f"  Всего: {total}  |  Покрытие: {(len(good)+len(weak))/total*100:.0f}%")
    print(f"{'='*65}\n")

    if bad:
        print("── ПРОБЛЕМНЫЕ ВОПРОСЫ (требуют переиндексации или ручных чанков) ──\n")
        for item in bad:
            q, hint, reason, _ = item
            print(f"  • {q!r}")
            print(f"    Ожидалось: {hint}  |  Причина: {reason}\n")

    if weak:
        print("── СЛАБЫЕ РЕЗУЛЬТАТЫ (поиск находит, но неуверенно) ──\n")
        for item in weak:
            q, hint, score, page, snippet = item
            print(f"  • {q!r}  score={score:.3f}")
            print(f"    {page}\n")


if __name__ == "__main__":
    run_tests()
